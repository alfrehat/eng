const fs = require('fs');
const path = require('path');

const nodeModulesDir = path.resolve(__dirname, '..', 'node_modules');
const contaminations = [];

const projectKeywords = ['kafr-inja', 'كفرنجة', 'المشاريع الهندسية', 'municipality', 'municipal_assets', 'road_segments', 'token_blacklist'];

function checkDir(dir) {
  try {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = path.join(dir, entry.name);
      if (entry.name === '.env' || entry.name.endsWith('.env') || entry.name.endsWith('.pem') || entry.name.endsWith('.key')) {
        contaminations.push({ type: 'SECRET_FILE', path: fullPath });
      }
      if (entry.name.endsWith('.sql') || entry.name.endsWith('.mdb')) {
        contaminations.push({ type: 'DATABASE_FILE', path: fullPath });
      }
      if (entry.isDirectory()) {
        if (entry.name === 'uploads' || entry.name === 'backups' || entry.name === 'database') {
          contaminations.push({ type: 'PROJECT_DIRECTORY', path: fullPath });
        }
        checkDir(fullPath);
      }
    }
  } catch (e) {}
}

checkDir(nodeModulesDir);

console.log('Contamination results in node_modules:');
console.log(JSON.stringify(contaminations, null, 2));
console.log(`Total contaminations found: ${contaminations.length}`);
