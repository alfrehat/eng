async function reseed() {
  await initializeDatabase();
  const dbDir = path.join(__dirname, '../database');
  const roles = JSON.parse(fs.readFileSync(path.join(dbDir, 'roles.json'), 'utf8'));

  const permsList = [];
  let idx = 1;
  for (const r of roles) {
    const list = STATIC_ROLES_PERMS[r.name] || [];
    for (const p of list) {
      permsList.push({
        id: `rp-${String(idx++).padStart(4, '0')}`,
        roleId: r.id,
        role_id: r.id,
        permissionId: p,
        permission_id: p,
        permission_code: p,
        is_granted: 1
      });
    }
  }

  fs.writeFileSync(path.join(dbDir, 'role_permissions.json'), JSON.stringify(permsList, null, 2), 'utf8');
  memDb.role_permissions = permsList;

  if (isPostgresActive()) {
    await dbRun('DELETE FROM role_permissions');
    for (const p of permsList) {
      await dbRun(
        'INSERT INTO role_permissions (id, "roleId", "permissionId", role_id, permission_id) VALUES ($1, $2, $3, $4, $5)',
        [p.id, p.roleId, p.permissionId, p.role_id, p.permission_id]
      );
    }
  }

  console.log(`✅ Successfully seeded ${permsList.length} role permissions matching all 15 roles!`);
  process.exit(0);
}

reseed();
